void keycode_to_string(int keycode,int shift_mask,char *buf,int type){
  char *letter;
  
  if (type == 1) {
    if (keycode - 1U < 766) {
      snprintf(buf,12,"%x %x",keycode,shift_mask);
      return;
    }
  }
  else if (type == 2) {
    if (keycode - 1U < 766) {
      snprintf(buf,0xc,"%d %d",keycode,shift_mask);
      return;
    }
  }
  else if ((type == 0) && (keycode - 1U < 119)) {
    if (shift_mask == 1) {
      letter = us_keymap[keycode][1];
    }
    else {
      letter = us_keymap[keycode][0];
    }
    snprintf(buf,0xc,"%s",letter);
    return;
  }
  return;
}



